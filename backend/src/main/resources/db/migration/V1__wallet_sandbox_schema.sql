CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(80) NOT NULL,
    phone VARCHAR(16) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_name_length CHECK (char_length(full_name) BETWEEN 2 AND 80)
);

CREATE TABLE wallets (
    user_id BIGINT PRIMARY KEY REFERENCES app_users(id),
    balance_minor BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT wallets_balance_bounds CHECK (balance_minor BETWEEN 0 AND 10000000000)
);

CREATE TABLE auth_sessions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX sessions_user_idx ON auth_sessions(user_id);
CREATE INDEX sessions_expiry_idx ON auth_sessions(expires_at);

CREATE TABLE wallet_transactions (
    id UUID PRIMARY KEY,
    reference VARCHAR(40) NOT NULL UNIQUE,
    type VARCHAR(16) NOT NULL CHECK (type IN ('TRANSFER', 'DEPOSIT')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED')),
    sender_id BIGINT NOT NULL REFERENCES app_users(id),
    recipient_id BIGINT NOT NULL REFERENCES app_users(id),
    amount_minor BIGINT NOT NULL CHECK (amount_minor BETWEEN 1 AND 100000000),
    currency VARCHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    note VARCHAR(160) NOT NULL DEFAULT '',
    idempotency_key UUID NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT transactions_idempotency UNIQUE (sender_id, idempotency_key),
    CONSTRAINT transaction_parties CHECK ((type = 'TRANSFER' AND sender_id <> recipient_id AND status = 'COMPLETED') OR (type = 'DEPOSIT' AND sender_id = recipient_id)),
    CONSTRAINT completed_time CHECK ((status = 'PENDING' AND completed_at IS NULL) OR (status = 'COMPLETED' AND completed_at IS NOT NULL))
);
CREATE INDEX transactions_sender_created_idx ON wallet_transactions(sender_id, created_at DESC);
CREATE INDEX transactions_recipient_created_idx ON wallet_transactions(recipient_id, created_at DESC);

CREATE TABLE webhook_events (
    event_id UUID PRIMARY KEY,
    deposit_id UUID NOT NULL REFERENCES wallet_transactions(id),
    payload_hash VARCHAR(64) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES app_users(id),
    action VARCHAR(48) NOT NULL,
    reference VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_actor_created_idx ON audit_events(actor_id, created_at DESC);
